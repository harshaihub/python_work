# String declaration
name = "Harshvardhan jadhav  "
course = "Python Programming  in vs studio"

# Concatenation
intro = "Hello, my name is " + name + "."

# Repetition
line = "-" * 30

# Indexing and slicing
first_letter = name[0]        # 'H'
last_three = name[-3:]        # 'han'

# String methods
upper_course = course.upper()   # 'PYTHON PROGRAMMING'
replaced_course = course.replace("Python", "C++")

# Display results
print(intro)
print(line)
print("First letter of name:", first_letter)
print("Last three letters of name:", last_three)
print("Course in uppercase:", upper_course)
print("Course after replacement:", replaced_course)
